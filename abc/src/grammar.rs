//! The grammar of one line of music. Splitting a file into tunes, fields and
//! lines is done by hand in [`crate::document`], which then calls
//! [`abc::music_items`] on each music line.

use crate::datatypes::*;
use num_rational::Rational32;

/// Turns the text between the quotes of `"..."` into a chord symbol or an annotation.
fn quoted_text(t: &str) -> MusicSymbol {
    let placement = match t.chars().next() {
        Some('^') => Some(Placement::Above),
        Some('_') => Some(Placement::Below),
        Some('<') => Some(Placement::Left),
        Some('>') => Some(Placement::Right),
        Some('@') => Some(Placement::Free),
        _ => None,
    };
    match placement {
        Some(placement) => MusicSymbol::Annotation {
            placement,
            text: t[1..].to_string(),
        },
        None => MusicSymbol::ChordSymbol(t.to_string()),
    }
}

peg::parser! {
/// Module generated by [rust_peg](https://crates.io/crates/peg)
///
/// Each public function corresponds to a rule and can be called with the text
/// of a single music line (no line terminator).
///
/// # Examples
/// ```
/// use abc::abc;
/// use ::abc::datatypes::*;
///
/// let items = abc::music_items("A2 B|").unwrap();
/// assert_eq!(items.len(), 4);
/// assert_eq!(items[1].kind, MusicSymbol::VisualBreak);
/// assert_eq!(items[3].span, Span::new(4, 5));
/// ```
pub grammar abc() for str {
    rule number() -> i32
        = n:$(['1'..='9']['0'..='9']*) {? n.parse().or(Err("a smaller number")) }

    rule space()
        = [' ' | '\t']+

    /// All symbols of one music line, with spans relative to the input.
    /// Text that cannot be parsed becomes [`MusicSymbol::Unknown`], so this
    /// rule only fails on input containing nothing parseable at all (never in practice).
    pub rule music_items() -> Vec<Symbol>
        = items:item()* { items.into_iter().flatten().collect() }

    rule item() -> Vec<Symbol>
        = be:bar_ending() { be }
        / s:position!() k:music_symbol() e:position!() { vec![Symbol::new(Span::new(s, e), k)] }
        / s:position!() u:$((![' ' | '\t' | '|'] [_])+) e:position!() {
              vec![Symbol::new(Span::new(s, e), MusicSymbol::Unknown(u.to_string()))]
          }

    /// A single symbol, for testing.
    pub rule music_symbol() -> MusicSymbol
        = f:inline_field() { f }
        / s:stem() "`"* { s }
        / d:decoration()+ { MusicSymbol::Decorations(d) }
        / r:rest() { r }
        / b:bar() { b }
        / e:ending() { e }
        / "{" a:"/"? { MusicSymbol::GraceStart { acciaccatura: a.is_some() } }
        / "}" { MusicSymbol::GraceEnd }
        / t:tuplet_start() { t }
        / "(" { MusicSymbol::SlurBegin }
        / ")" { MusicSymbol::SlurEnd }
        / b:broken_rhythm() { b }
        / "&" { MusicSymbol::Overlay }
        / "\"" t:$((!['"'] [_])*) "\"" { quoted_text(t) }
        / space() { MusicSymbol::VisualBreak }

    rule inline_field() -> MusicSymbol
        = s:position!() "[" n:$(['A'..='Z' | 'a'..='z']) ":" v:$((![']'] [_])*) "]" e:position!() {
            MusicSymbol::InlineField(InfoField::new(
                n.chars().next().unwrap(),
                v.trim(),
                Span::new(s, e),
            ))
        }

    rule broken_rhythm() -> MusicSymbol
        = op:$(">"*<1,3> / "<"*<1,3>) !['>' | '<'] {
            MusicSymbol::BrokenRhythm {
                first_longer: op.starts_with('>'),
                dots: op.len() as u8,
            }
        }

    pub rule stem() -> MusicSymbol
        = d:decoration()* c:stem_core() l:length()? t:tie()? {
            let (pitches, inner) = c;
            MusicSymbol::Stem {
                pitches,
                length: inner * l.unwrap_or(Rational32::from_integer(1)),
                decorations: d,
                tie: t, // the outer tie: "C-" or "[CEG]-"
            }
        }

    // A single note or a chord, plus the length written inside the chord
    // ("[C2E2G2]" counts as a chord of length 2; the first note decides).
    rule stem_core() -> (Vec<Pitch>, Rational32)
        = "[" p:chord_pitch()+ "]" {
            let inner = p[0].1;
            (p.into_iter().map(|(p, _)| p).collect(), inner)
        }
        / p:pitch() { (vec![p], Rational32::from_integer(1)) }

    // A pitch inside a chord may carry its own length and tie: [C2-EG]
    rule chord_pitch() -> (Pitch, Rational32)
        = p:pitch() l:length()? t:tie()? {
            (Pitch { tie: t, ..p }, l.unwrap_or(Rational32::from_integer(1)))
        }

    // Parses raw pitch data (no tie)
    rule pitch() -> Pitch
        = a:accidental()? n:note_uppercase() o:octave()? {
            Pitch::new(n, o.unwrap_or(1), a, None)
        } /
            a:accidental()? n:note_lowercase() o:octave()? {
            Pitch::new(n, o.unwrap_or(1) + 1, a, None)
        } /
            n:raised_uppercase() o:octave()? {
            Pitch::raised(n, o.unwrap_or(1))
        } /
            n:raised_lowercase() o:octave()? {
            Pitch::raised(n, o.unwrap_or(1) + 1)
        }

    // Sharp notation: I K N Q W are C# D# F# G# A#; they take no accidentals
    pub rule raised_uppercase() -> Note
        = "I" { Note::C } /
          "K" { Note::D } /
          "N" { Note::F } /
          "Q" { Note::G } /
          "W" { Note::A }

    pub rule raised_lowercase() -> Note
        = "i" { Note::C } /
          "k" { Note::D } /
          "n" { Note::F } /
          "q" { Note::G } /
          "w" { Note::A }

    pub rule note_uppercase() -> Note
        = "A" { Note::A } /
          "B" { Note::B } /
          "C" { Note::C } /
          "D" { Note::D } /
          "E" { Note::E } /
          "F" { Note::F } /
          "G" { Note::G }

    pub rule note_lowercase() -> Note
        = "a" { Note::A } /
          "b" { Note::B } /
          "c" { Note::C } /
          "d" { Note::D } /
          "e" { Note::E } /
          "f" { Note::F } /
          "g" { Note::G }

    rule tie() -> Tie
        = ".-" { Tie::Dotted } /
          "-" { Tie::Solid }

    rule bar_text() -> &'input str
        = $(([':' | '|' | '\\' | ']'] / "[" &['|'])+)

    pub rule bar() -> MusicSymbol
        = b:bar_text() { MusicSymbol::Bar(b.to_string()) }

    // shorthand endings: "|1" and ":|2" mean the same as "|[1" and ":|[2"
    rule bar_ending() -> Vec<Symbol>
        = s:position!() b:bar_text() m:position!() n:number() e:position!() {?
            if b.ends_with('|') {
                Ok(vec![
                    Symbol::new(Span::new(s, m), MusicSymbol::Bar(b.to_string())),
                    Symbol::new(Span::new(m, e), MusicSymbol::Ending(n)),
                ])
            } else {
                Err("bar line ending in '|' before an ending number")
            }
        }

    rule decoration() -> Decoration
        = d:decoration_symbol() space()? { d }

    rule decoration_symbol() -> Decoration
        = "." { Decoration::Staccato } /
          "~" { Decoration::Roll } /
          "H" { Decoration::Fermata } /
          "L" { Decoration::Accent } /
          "M" { Decoration::LowerMordent } /
          "O" { Decoration::Coda } /
          "P" { Decoration::UpperMordent } /
          "S" { Decoration::Segno } /
          "T" { Decoration::Trill } /
          "u" { Decoration::UpBow } /
          "v" { Decoration::DownBow } /
          "!" d:$((!['!'][_])+) "!" { Decoration::Unresolved(d.to_string()) } /
          "+" d:$((!['+'][_])+) "+" { Decoration::Unresolved(d.to_string()) }

    rule accidental() -> Accidental
        = "^^" { Accidental::DoubleSharp } /
          "__" { Accidental::DoubleFlat } /
          "^" { Accidental::Sharp } /
          "_" { Accidental::Flat } /
          "=" { Accidental::Natural }

    rule octave() -> i8
        = p:$([',' | '\'']+) {?
            let mut octave: i32 = 1;
            for c in p.chars() {
                if c == ',' { octave -= 1 } else { octave += 1 }
            }
            i8::try_from(octave).or(Err("a reasonable octave"))
        }

    rule length() -> Rational32
        // "/2" -> 1/2
        = "/" n:number() { Rational32::new(1, n) }
        // "/" or "//" or "///" -> 1/2, 1/4, 1/8
        / s:$("/"+) {? slashes(s.len()) }
        // "3/2" -> 3/2
        / n1:number() "/" n2:number() { Rational32::new(n1, n2) }
        // "3/" -> 3/2, "3//" -> 3/4
        / n:number() s:$("/"+) {? slashes(s.len()).map(|r| r * n) }
        // "3" -> 3
        / n:number() { Rational32::from_integer(n) }

    pub rule rest() -> MusicSymbol
        = "z" l:length()? { MusicSymbol::Rest(Rest::Note(l.unwrap_or(Rational32::from_integer(1)))) }
        / "Z" n:number()? { MusicSymbol::Rest(Rest::Measure(n.unwrap_or(1))) }
        / "x" l:length()? { MusicSymbol::Rest(Rest::NoteHidden(l.unwrap_or(Rational32::from_integer(1)))) }
        / "X" n:number()? { MusicSymbol::Rest(Rest::MeasureHidden(n.unwrap_or(1))) }

    pub rule ending() -> MusicSymbol
        = "[" n:number() { MusicSymbol::Ending(n) }

    // "(3", "(3:2", "(3:2:3", "(3::3"
    rule tuplet_start() -> MusicSymbol
        = "(" p:number() q:(":" q:number()? { q })? r:(":" r:number()? { r })? {?
            if (2..=9).contains(&p) {
                Ok(MusicSymbol::TupletStart { p, q: q.flatten(), r: r.flatten() })
            } else {
                Err("a tuplet of 2 to 9 notes")
            }
        }

    /// The tokens of the text of a `w:` field, with spans relative to the
    /// input. Every text parses.
    pub rule lyric_items() -> Vec<LyricToken>
        = space()? t:(i:lyric_item() space()? { i })* { t }

    rule lyric_item() -> LyricToken
        = s:position!() k:lyric() e:position!() { LyricToken::new(Span::new(s, e), k) }

    rule lyric() -> Lyric
        = "_" { Lyric::Hold }
        / "*" { Lyric::Skip }
        / "|" { Lyric::Bar }
        / t:lyric_text() h:"-"? { Lyric::Syllable { text: t, hyphen: h.is_some() } }
        // a hyphen after a space or another hyphen is a syllable of its own
        / "-" { Lyric::Syllable { text: String::new(), hyphen: true } }

    rule lyric_text() -> String
        = c:lyric_char()+ { c.into_iter().collect() }

    // "\-" is a hyphen that does not end the syllable, "~" a space that does not
    rule lyric_char() -> char
        = "\\-" { '-' }
        / "~" { ' ' }
        / c:$(![' ' | '\t' | '-' | '_' | '*' | '|' | '~'] [_]) { c.chars().next().unwrap() }
}}

/// `n` slashes halve the length `n` times.
fn slashes(n: usize) -> Result<Rational32, &'static str> {
    if n <= 8 {
        Ok(Rational32::new(1, 1 << n))
    } else {
        Err("at most 8 slashes")
    }
}
